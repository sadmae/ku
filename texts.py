def t(lang: str, key: str, **kwargs: object) -> str:
    pack = STRINGS.get(lang) or STRINGS["ru"]
    template = pack.get(key, STRINGS["ru"].get(key, key))
    if not isinstance(template, str):
        return str(key)
    return re.sub(r"\{(\w+)\}", lambda match: str(kwargs.get(match.group(1), match.group(0))), template)


def example_labels(lang: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    pack = STRINGS.get(lang) or STRINGS["ru"]
    nodes = pack["exn"]
    options = pack["exo"]
    assert isinstance(nodes, list) and isinstance(options, list)
    return tuple(str(item) for item in nodes), tuple(str(item) for item in options)
